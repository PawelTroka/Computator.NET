test('the displayed chart is generated by the real renderer', async ({ page }) => {
  await page.goto('/');
  await page.locator('#expressionTextArea textarea').fill('x');
  const pending = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v2/chart' && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Draw chart!' }).click();
  const response = await pending;
  expect(response.ok()).toBeTruthy();
  expect(response.headers()['content-type']).toContain('image/png');
  const image = page.getByRole('img', { name: 'x', exact: true });
  await expect.poll(() => image.evaluate((element: HTMLImageElement) => element.naturalWidth)).toBeGreaterThan(100);
  // Inspect the exact blob displayed by the UI. Chromium can omit the CDP
  // response body after fetch().blob() consumes it, despite a valid transfer.
  const bytes = Buffer.from(await image.evaluate(async (element: HTMLImageElement) =>
    Array.from(new Uint8Array(await (await fetch(element.src)).arrayBuffer()))));
  expect(bytes.subarray(0, 8).toString('hex')).toBe('89504e470d0a1a0a');
  expect(bytes.length).toBeGreaterThan(1024);
});

test('same-origin proxy rejects cross-site callers and protects the backend token', async ({ request }) => {
  expect((await request.get('http://127.0.0.1:60997/api/calculate/2x/3')).status()).toBe(403);
  expect((await request.get('/api/calculate/2x/3', { headers: { Origin: 'https://example.com' } })).status()).toBe(403);
  const response = await request.get('/api/calculate/2x/3');
  expect(response.ok()).toBeTruthy();
  expect(await response.text()).toBe('6');
  expect((await request.get('/api/does-not-exist')).status()).toBe(404);
  const execution = { operation: 'calculate', expression: '6/3' };
  expect((await request.post('http://127.0.0.1:60997/api/v2/execute', { data: execution })).status()).toBe(403);
  expect((await request.post('/api/v2/execute', { data: execution, headers: { Origin: 'https://example.com' } })).status()).toBe(403);
  expect((await request.post('/api/v2/execute', { data: execution, headers: { 'Sec-Fetch-Site': 'cross-site' } })).status()).toBe(403);
  expect((await request.post('/api/v2/execute', { data: execution, headers: { Host: 'example.com' } })).status()).toBe(403);
  expect((await request.post('/api/v2/execute', { data: '6/3', headers: { 'Content-Type': 'text/plain' } })).status()).toBe(415);
  expect((await request.post('/api/v2/execute', { data: { expression: '1'.repeat(262145) } })).status()).toBe(413);
  const calculation = await request.post('/api/v2/execute', { data: execution });
  expect(calculation.ok()).toBeTruthy();
  expect(await calculation.json()).toEqual({ result: '2' });
});
